#!/usr/bin/env python3
"""Assemble the C2 PC-handoff package from the Tamarind result folders.

Reads the raw result folders and writes, under challenges/02-tnfa/handoff/:
  designs/all-designs.csv     every X2 design with metrics + sequence
  designs/designs.csv         the clean shortlist for the next folds
  designs/pdb/*.pdb           the shortlist complexes
  sequences/*.fasta           shortlist binders + the human and mouse targets
  boltz/fold-human-*.yaml     Boltz-2 input for each shortlist design (human TNF)
  boltz/fold-mouse-*.yaml     Boltz-2 input for the top design (mouse TNF)
  records/                    job JSONs, triage CSVs, fold metrics
  notes/                      copies of the challenge notes and figures
  data-raw/                   the two original result zips

Run from anywhere:  python prepare_handoff.py
"""
from __future__ import annotations

import csv
import pathlib
import shutil
import sys

import numpy as np
import pandas as pd
from Bio.Align import PairwiseAligner
from Bio.Align import substitution_matrices

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from triage_rfd3 import read_pdb  # noqa: E402

C2 = pathlib.Path(__file__).resolve().parents[2]          # challenges/02-tnfa
HANDOFF = C2 / "handoff"
X2 = C2 / "data/tamarind/x2"
X1 = C2 / "data/tamarind/x1"
EPI = C2 / "data/epitope-analysis"
NOTES = C2 / "notes"
DESIGNS = HANDOFF / "designs"
SEQS = HANDOFF / "sequences"
BOLTZ = HANDOFF / "boltz"
RECORDS = HANDOFF / "records"

SHORTLIST_MAX = 10
SHORTLIST_MIN_ATOMS4 = 80
SHORTLIST_MIN_D = 2.0


def load_uniprot(path):
    import json
    return json.loads(pathlib.Path(path).read_text())["sequence"]["value"]


def human_and_mouse_targets(ref_pdb):
    """The fold constructs: the 1TNF construct mapped onto P01375 and P06804 by alignment."""
    chains = read_pdb(ref_pdb)
    target = chains[max(chains, key=lambda c: len(chains[c]["res"]))]["sequence"]
    human = load_uniprot(EPI / "uniprot_P01375_human_TNF.json")
    mouse = load_uniprot(EPI / "uniprot_P06804_mouse_TNF.json")

    aligner = PairwiseAligner(mode="global", open_gap_score=-10, extend_gap_score=-0.5)
    aligner.substitution_matrix = substitution_matrices.load("BLOSUM62")
    # target construct -> human precursor
    aln1 = aligner.align(human, target)[0]
    t2h, substitutions = {}, []
    for (h0, h1), (t0, t1) in zip(*aln1.aligned):
        for k in range(h1 - h0):
            t2h[t0 + k] = h0 + k
            if human[h0 + k] != target[t0 + k]:
                substitutions.append(f"construct {t0 + k + 1} / P01375 {h0 + k + 1}: {human[h0 + k]}->{target[t0 + k]}")
    h_positions = sorted(t2h.values())
    # human mature (77-233) -> mouse mature (80-235)
    aln2 = aligner.align(human[76:], mouse[79:])[0]
    h2m = {}
    for (h0, h1), (m0, m1) in zip(*aln2.aligned):
        for k in range(h1 - h0):
            h2m[76 + h0 + k] = 79 + m0 + k
    positions = [h2m[p] for p in h_positions if p in h2m]
    mouse_construct = "".join(mouse[p] for p in positions)
    meta = {
        "human": {"construct": target,
                  "uniprot_residues": f"{h_positions[0] + 1}-{h_positions[-1] + 1}",
                  "substitutions_vs_uniprot": substitutions,
                  "length": len(target)},
        "mouse": {"construct": mouse_construct,
                  "uniprot_residues": f"{min(positions) + 1}-{max(positions) + 1}",
                  "unaligned_positions": len(h_positions) - len(positions),
                  "length": len(mouse_construct)},
    }
    return meta


def write_fasta(path, records):
    with open(path, "w") as fh:
        for name, desc, seq in records:
            fh.write(f">{name} {desc}\n{seq}\n")


def boltz_yaml(path, binder, target, note):
    body = ["# Boltz-2 input — generated by prepare_handoff.py",
            f"# {note}",
            "version: 1",
            "sequences:"]
    for cid, seq in (("A", binder), ("B", target), ("C", target), ("D", target)):
        body += [f"  - protein:", f"      id: {cid}", f"      sequence: {seq}"]
    pathlib.Path(path).write_text("\n".join(body) + "\n")


def main():
    for d in (HANDOFF, DESIGNS / "pdb", SEQS, BOLTZ, RECORDS, HANDOFF / "data-raw"):
        d.mkdir(parents=True, exist_ok=True)

    # ---- all-designs table (must exist: run triage_rfd3.py first)
    src = X2 / "x2-triage.csv"
    df = pd.read_csv(src)
    root = X2 / "extracted/c2-x2-rfd3-s1-groove"
    meta = human_and_mouse_targets(root / df.iloc[0]["pdb"])
    print("human construct: %s (%s)" % (meta["human"]["uniprot_residues"], meta["human"]["construct"][:20] + "..."))
    print("  substitutions vs P01375:", meta["human"]["substitutions_vs_uniprot"] or "none")
    print("mouse construct: %s (%s)" % (meta["mouse"]["uniprot_residues"], meta["mouse"]["construct"][:20] + "..."))
    shutil.copy(src, RECORDS / "x2-triage.csv")
    shutil.copy(src, DESIGNS / "all-designs.csv")

    # ---- shortlist
    mask = (df["site_any"]) & (df["min_d"] >= SHORTLIST_MIN_D) & (df["atoms4"] >= SHORTLIST_MIN_ATOMS4)
    short = df[mask].sort_values("atoms4", ascending=False).head(SHORTLIST_MAX).copy()
    short["rank"] = range(1, len(short) + 1)
    short.to_csv(DESIGNS / "designs.csv", index=False)
    print(f"shortlist: {len(short)} designs")
    print(short[["rank", "design", "binder_len", "min_d", "atoms4", "helix_frac"]].to_string(index=False))

    for _, r in short.iterrows():
        shutil.copy(root / r["pdb"], DESIGNS / "pdb" / r["design"])

    write_fasta(SEQS / "shortlist-binders.fasta",
                [(r["design"], f"length={r['binder_len']} atoms4={r['atoms4']}", r["sequence"])
                 for _, r in short.iterrows()])
    site_all = df[df["site_any"]]
    write_fasta(SEQS / "all-site-binders.fasta",
                [(r["design"], f"length={r['binder_len']} atoms4={r['atoms4']}", r["sequence"])
                 for _, r in site_all.iterrows()])
    write_fasta(SEQS / "targets.fasta", [
        ("human-TNF-construct", f"P01375 residues {meta['human']['uniprot_residues']}", meta["human"]["construct"]),
        ("mouse-TNF-construct", f"P06804 residues {meta['mouse']['uniprot_residues']}", meta["mouse"]["construct"]),
    ])

    # ---- boltz templates
    for _, r in short.iterrows():
        boltz_yaml(BOLTZ / f"fold-human-{r['design']}.yaml", r["sequence"], meta["human"]["construct"],
                   f"human TNF fold of {r['design']} (X2, {r['binder_len']} aa, atoms4 {r['atoms4']}, min_d {r['min_d']})")
    top = short.iloc[0]
    boltz_yaml(BOLTZ / f"fold-mouse-{top['design']}.yaml", top["sequence"], meta["mouse"]["construct"],
               f"mouse TNF fold of {top['design']} (cross-species check)")
    print("wrote", len(list(BOLTZ.glob('*.yaml'))), "boltz yaml files")

    # ---- x1 consolidated metrics
    frames = []
    for tag in ("s1-antibody-epitope", "s2-cation-switch", "s3-diagnostic"):
        f = X1 / f"extracted/c2-x1-{tag}/final_ranked_designs/all_designs_metrics.csv"
        if not f.exists():
            print("missing:", f)
            continue
        d = pd.read_csv(f)
        d["set"] = tag
        frames.append(d)
    if frames:
        x1 = pd.concat(frames, ignore_index=True)
        x1.to_csv(RECORDS / "x1-triage.csv", index=False)
        print("x1-triage.csv:", x1.shape, "| columns:", list(x1.columns)[:14])

    # ---- fold metrics + job records + zips + notes
    shutil.copy(X2 / "extracted/c2-x2-boltz-fold-best/metrics.csv", RECORDS / "x2-fold-metrics.csv")
    for name in ("x1-tamarind-jobs.json", "x2-tamarind-jobs.json", "x2-fold-job.json"):
        shutil.copy(NOTES / name, RECORDS / name)
    for z in (X2 / "c2-x2-rfd3-s1-groove.zip", X2 / "c2-x2-boltz-fold-best.zip"):
        shutil.copy(z, HANDOFF / "data-raw" / z.name)

    notes_dst = HANDOFF / "notes"
    notes_dst.mkdir(exist_ok=True)
    for md in (NOTES.glob("*.md")):
        shutil.copy(md, notes_dst / md.name)
    figures_dst = notes_dst / "figures"
    figures_dst.mkdir(exist_ok=True)
    for fig in (NOTES / "figures").glob("*"):
        shutil.copy(fig, figures_dst / fig.name)
    print("notes copied:", len(list(notes_dst.glob('*.md'))), "md files")
    print("handoff assembled at", HANDOFF)


if __name__ == "__main__":
    main()
