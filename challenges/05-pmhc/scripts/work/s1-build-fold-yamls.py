#!/usr/bin/env python3
"""Build Boltz-2 fold yamls for the stage-1 shortlist (G12D arm).

Input: the stage-0 pose-screen CSV; only `pass` == True rows are built.
Each design becomes one yaml: the design's own binder sequence (chain D from
the RFD4 cif, no MSA) plus the G12D pMHC target chains with their MSAs
(A=HLA 276, B=b2m 99, C=peptide 10). The WT and peptide-free arms for the
tri-state stage are generated by --state wt / --state free (the WT target
sequences come from the organizer 7OW5 file).

Output: <out>/<design-id>.yaml where design-id = <batch>/<run>/<design-stem>,
slashes flattened to "__".

Usage:
  .venv/bin/python s1-build-fold-yamls.py \
      --screen ~/c5-work/s0/pose-screen.csv \
      --designs ~/c5-work/c1 --out ~/c5-work/s1/folds --state g12d
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import pathlib

import gemmi

AA3 = {"ALA": "A", "ARG": "R", "ASN": "N", "ASP": "D", "CYS": "C", "GLN": "Q",
       "GLU": "E", "GLY": "G", "HIS": "H", "ILE": "I", "LEU": "L", "LYS": "K",
       "MET": "M", "PHE": "F", "PRO": "P", "SER": "S", "THR": "T", "TRP": "W",
       "TYR": "Y", "VAL": "V", "MSE": "M"}

REPO = pathlib.Path(__file__).resolve().parents[4]
MSA_DIR = REPO / "challenges/05-pmhc/inputs/msa"
OW6 = REPO / "challenges/05-pmhc/inputs/7OW6-G12D-noTCR.pdb"
OW5 = REPO / "challenges/05-pmhc/inputs/7OW5-WT-noTCR.pdb"
FREE = REPO / "challenges/05-pmhc/inputs/7OW6-peptide-free.pdb"


def chain_seq(st: gemmi.Structure, chain: str) -> str:
    c = st[0].find_chain(chain)
    return "".join(AA3[r.name] for r in c if r.name in AA3)


def msa_path(seq: str) -> str:
    tag = hashlib.sha1(seq.encode()).hexdigest()[:12]
    hits = sorted(MSA_DIR.glob(f"{tag}-d*.a3m"))
    return str(hits[0]) if hits else "empty"


def yaml_text(chains: list[tuple[str, str, bool]]) -> str:
    lines = ["version: 1", "sequences:"]
    for cid, seq, use_msa in chains:
        msa = msa_path(seq) if use_msa else "empty"
        lines += ["  - protein:", f"      id: {cid}",
                  f"      sequence: {seq}", f"      msa: {msa}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--screen", type=pathlib.Path, required=True)
    ap.add_argument("--designs", type=pathlib.Path, required=True)
    ap.add_argument("--out", type=pathlib.Path, required=True)
    ap.add_argument("--state", choices=("g12d", "wt", "free"), default="g12d")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    # target chains per state, all from the ORGANIZER files — the challenge's
    # own shipped targets (the organizer WT HLA carries the same missing
    # leading Gly-1 as the RCSB deposition; verbatim use keeps the screen
    # delta on exactly the targets the organizers define)
    if args.state == "wt":
        st_wt = gemmi.read_structure(str(OW5))
        target = [("A", chain_seq(st_wt, "A"), True),
                  ("B", chain_seq(st_wt, "B"), True),
                  ("C", chain_seq(st_wt, "C"), False)]
    elif args.state == "free":
        st_free = gemmi.read_structure(str(FREE))
        target = [("A", chain_seq(st_free, "A"), True),
                  ("B", chain_seq(st_free, "B"), True)]
    else:
        st_g12d = gemmi.read_structure(str(OW6))
        target = [("A", chain_seq(st_g12d, "A"), True),
                  ("B", chain_seq(st_g12d, "B"), True),
                  ("C", chain_seq(st_g12d, "C"), False)]

    rows = [r for r in csv.DictReader(open(args.screen))
            if r["pass"] == "True"]
    if args.limit:
        rows = rows[:args.limit]
    args.out.mkdir(parents=True, exist_ok=True)
    built = skipped = 0
    for r in rows:
        cif = args.designs / f"{r['design']}.cif"
        if not cif.exists():
            skipped += 1
            continue
        st = gemmi.read_structure(str(cif))
        bseq = chain_seq(st, "D")
        if not bseq:
            skipped += 1
            continue
        did = r["design"].replace("/", "__")
        ytext = yaml_text(target + [("D", bseq, False)])
        out = args.out / f"{did}__{args.state}.yaml"
        # the design's own pose: keep a copy of the cif beside the yaml so the
        # scorer can compare fold-vs-generator poses
        out.write_text(ytext)
        built += 1
    print(f"{args.state}: built {built} yamls, skipped {skipped} "
          f"(of {len(rows)} passing rows) under {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
